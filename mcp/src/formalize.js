const { compile } = require('../../fret-electron/app/parser/FretSemantics');
const constants = require('../../fret-electron/app/parser/Constants');
const { formalizeInput } = require('./schemas');

const representations = Object.freeze({
  'ft-inf': { field: 'ftInfAUExpanded', semantics: 'ft' },
  'ft-fin': { field: 'ftExpanded', semantics: 'ft' },
  'pt-smv': { field: 'ptExpanded', semantics: 'pt' },
  'pt-lustre': { field: 'CoCoSpecCode', semantics: 'pt' }
});
const unavailable = new Set([
  constants.nonsense_semantics,
  constants.undefined_semantics,
  constants.unhandled_semantics
]);

/**
 * Synchronous, local computation; no MCP transport or solver is started.
 *
 * Input: {requirements: [{id, fretish}], representations: ['ft-inf', ...],
 *         variables?: [{name, type: 'bool' | 'int' | 'real'}]}.
 * IDs and requested representations must be unique and nonempty. Invalid
 * request structure throws TypeError before compiling any requirements.
 * Each requirement otherwise receives its own result, including on failure.
 *
 * Status is formalized only when every requested representation was produced;
 * partial/not_formalized mean some/none were produced, invalid means rejected
 * input text, and error means FRET raised a computation exception.
 * These statuses say nothing about realizability or implementation correctness.
 *
 * FRET explanations are returned as HTML, as generated by FRET. Durations in
 * formulas are discrete steps; this function performs no physical-time
 * conversion. Diagnostic positions are one-based UTF-16 positions, or null.
 * Supplying variables (including []) enables strict declaration/type checking
 * in one component. Omitting variables leaves declared types unchecked.
 * Retain the request with its result to preserve that evidence boundary.
 *
 * Example:
 * formalizeRequirements({
 *   requirements: [{id: 'R1', fretish: 'Controller shall always satisfy enabled'}],
 *   representations: ['ft-inf', 'pt-lustre']
 * });
 */
function formalizeRequirements(request) {
  const parsed = formalizeInput.safeParse(request);
  if (!parsed.success) throw new TypeError(parsed.error.message);
  const { requirements, representations: requested, variables } = parsed.data;
  const variableTypes = variables === undefined ? undefined : new Map(variables.map(({ name, type }) => [name, type]));
  const components = new Map();

  const results = requirements.map(({ id, fretish }) => {
    const result = { id, status: 'not_formalized', formulas: [], explanation: null, diagnostics: [] };
    try {
      const compiled = compile(fretish, variableTypes);
      if (compiled.parseErrors) {
        result.status = 'invalid';
        result.diagnostics = compiled.diagnostics;
        return result;
      }
      const semantics = compiled.collectedSemantics;
      if (variableTypes !== undefined && semantics.component_name) components.set(id, semantics.component_name);
      const description = semantics.probability === 'bound'
        ? semantics.probabilistic_description : semantics.description;
      if (typeof description === 'string') {
        result.explanation = { format: 'html', text: description };
      }
      if (semantics.type === 'freeForm') {
        result.diagnostics.push({
          code: 'freeform_text',
          message: 'FRET treats quoted text as free form and does not formalize it.',
          location: null
        });
        return result;
      }
      // The ordinary LTL fields do not encode the probability bound. Returning
      // them as a successful formalization would silently weaken the input.
      if (semantics.probability !== 'null') {
        result.diagnostics.push({
          code: 'unsupported_representation',
          message: 'The requested LTL/Lustre representations do not encode this probabilistic requirement. This entry point does not expose PCTL.',
          location: null
        });
        return result;
      }
      for (const representation of requested) {
        const target = representations[representation];
        const formula = semantics[target.field];
        if (typeof formula !== 'string' || formula.trim().length === 0 ||
            unavailable.has(formula) || unavailable.has(semantics[target.semantics])) {
          result.diagnostics.push({
            code: 'formula_unavailable',
            representation,
            message: `FRET did not produce a ${representation} formula.`,
            location: null
          });
        } else {
          result.formulas.push({ representation, formula });
        }
      }
      if (result.formulas.length === requested.length) result.status = 'formalized';
      else if (result.formulas.length > 0) result.status = 'partial';
    } catch (error) {
      result.status = 'error';
      result.formulas = [];
      result.diagnostics = [{
        code: 'computation_error',
        message: error instanceof Error ? `${error.name}: ${error.message}` : String(error),
        location: null
      }];
    }
    return result;
  });
  // A declaration environment belongs to one component. Reject every compiled
  // component in an ambiguous batch, independently of requirement ordering.
  if (new Set(components.values()).size > 1) {
    for (const result of results) {
      if (!components.has(result.id)) continue;
      result.status = 'invalid';
      result.formulas = [];
      result.diagnostics.push({
        code: 'component_mismatch',
        message: 'A typed formalization batch must contain only one FRETish component. Submit separate requests for separate components.',
        location: null
      });
    }
  }
  return { representations: [...requested], time_basis: 'discrete_steps', results };
}

module.exports = { formalizeRequirements };
